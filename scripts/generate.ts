import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { parse } from 'yaml'

const root = join(import.meta.dirname, '..')
const specDirectory = join(root, 'spec/books')
const outputDirectory = join(root, 'src/books/generated')
const indexFile = join(root, 'src/books/index.ts')
const banner = '// Generated by scripts/generate.ts from Zoho\'s OpenAPI documents. Do not edit.\n'

interface SchemaNode {
  readonly $ref?: string
  readonly type?: string
  readonly format?: string
  readonly description?: string
  readonly enum?: ReadonlyArray<string | number>
  readonly properties?: Readonly<Record<string, SchemaNode>>
  readonly required?: ReadonlyArray<string>
  readonly items?: SchemaNode
  readonly allOf?: ReadonlyArray<SchemaNode>
  readonly readOnly?: boolean
}

interface ParameterNode {
  readonly $ref?: string
  readonly name: string
  readonly in: 'header' | 'path' | 'query'
  readonly description?: string
  readonly required?: boolean
  readonly schema?: SchemaNode
}

interface OperationNode {
  readonly operationId: string
  readonly summary?: string
  readonly deprecated?: boolean
  readonly parameters?: ReadonlyArray<ParameterNode>
  readonly requestBody?: { readonly required?: boolean; readonly content?: Readonly<Record<string, { readonly schema?: SchemaNode }>> }
  readonly responses?: Readonly<Record<string, { readonly content?: Readonly<Record<string, { readonly schema?: SchemaNode }>> }>>
  readonly security?: ReadonlyArray<Readonly<Record<string, ReadonlyArray<string>>>>
}

interface Document {
  readonly info: { readonly title: string }
  readonly paths: Readonly<Record<string, Readonly<Record<string, unknown>>>>
  readonly components?: {
    readonly schemas?: Readonly<Record<string, SchemaNode>>
    readonly parameters?: Readonly<Record<string, ParameterNode>>
  }
}

const methods = ['get', 'post', 'put', 'delete'] as const
const reservedNames = new Set([
  'Array', 'Boolean', 'Date', 'Error', 'Function', 'Map', 'Number', 'Object', 'Promise', 'Record', 'Set', 'String', 'Symbol',
  'Blob', 'Uint8Array', 'Schema', 'W', 'operation', 'ZohoFile',
])

/** Path segments Zoho writes as a regular expression without declaring a parameter for them. */
const undeclaredPathParameters: Readonly<Record<string, ReadonlyArray<string>>> = {
  '/reportingtags/(\\d+)/options/all': ['tag_id'],
}

const words = (name: string): string[] => name.split(/[^A-Za-z0-9]+/).filter((word) => word !== '')
const pascal = (name: string): string => words(name).map((word) => word[0]!.toUpperCase() + word.slice(1)).join('')
const camel = (name: string): string => {
  const value = pascal(name)
  return value[0]!.toLowerCase() + value.slice(1)
}
const key = (name: string): string => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name))
const refName = (ref: string): string => ref.slice(ref.lastIndexOf('/') + 1)

function comment(text: string | undefined, indent: string): string {
  if (text === undefined) return ''
  const plain = text.replace(/<[^>]+>/g, '').replace(/\*\//g, '* /').replace(/\s+/g, ' ').trim()
  return plain === '' ? '' : `${indent}/** ${plain} */\n`
}

class Module {
  readonly name: string
  private readonly schemas: Readonly<Record<string, SchemaNode>>
  private readonly parameters: Readonly<Record<string, ParameterNode>>
  private readonly names = new Map<string, string>()
  private readonly taken = new Set<string>()
  private readonly responseDeclarations = new Map<string, string>()
  private readonly inputDeclarations = new Map<string, string>()
  private readonly operations: string[] = []

  constructor(readonly file: string, private readonly document: Document) {
    this.name = pascal(file.replace(/\.yml$/, ''))
    this.schemas = document.components?.schemas ?? {}
    this.parameters = document.components?.parameters ?? {}
  }

  private schema(name: string): SchemaNode {
    const found = this.schemas[name]
    if (found === undefined) throw new Error(`${this.file}: schema ${name} is referenced but not defined`)
    return found
  }

  /** Follows references to the schema that carries the shape. */
  private resolve(node: SchemaNode): SchemaNode {
    return node.$ref === undefined ? node : this.resolve(this.schema(refName(node.$ref)))
  }

  private merged(node: SchemaNode): SchemaNode {
    if (node.allOf === undefined) return node
    const members = node.allOf.map((member) => this.merged(this.resolve(member)))
    return {
      type: 'object',
      properties: Object.assign({}, node.properties, ...members.map((member) => member.properties ?? {})),
      required: [...(node.required ?? []), ...members.flatMap((member) => member.required ?? [])],
    }
  }

  private kind(node: SchemaNode): 'any' | 'array' | 'boolean' | 'number' | 'object' | 'record' | 'string' {
    const shape = this.merged(node)
    if (shape.type === 'array') return 'array'
    if (shape.properties !== undefined && Object.keys(shape.properties).length > 0) return 'object'
    switch (shape.type) {
      case 'object': return 'record'
      case 'string': return 'string'
      case 'integer':
      case 'number': return 'number'
      case 'boolean': return 'boolean'
      default: return 'any'
    }
  }

  private declare(component: string, use: 'input' | 'response'): string {
    const id = `${use} ${component}`
    const existing = this.names.get(id)
    if (existing !== undefined) return existing
    let name = `${pascal(component)}${use === 'response' || /request$/i.test(component) ? '' : 'Input'}`
    if (use === 'input' && this.taken.has(name)) name = `${name}Input`
    while (this.taken.has(name) || reservedNames.has(name)) name = `${name}_`
    this.taken.add(name)
    this.names.set(id, name)
    return name
  }

  // Responses: Effect schemas, because the data is untrusted.

  private responseItem(node: SchemaNode): string {
    if (node.$ref !== undefined) {
      const component = refName(node.$ref)
      const target = this.schema(component)
      const kind = this.kind(target)
      if (kind === 'object' || kind === 'array') return this.responseDeclaration(component)
      return this.responseItem(target)
    }
    const shape = this.merged(node)
    switch (this.kind(shape)) {
      case 'array': return `W.Arr(${shape.items === undefined ? 'W.Any' : this.responseItem(shape.items)})`
      case 'object': return this.responseStruct(shape, '  ')
      case 'record': return 'W.Any'
      case 'string': return 'W.Str'
      case 'number': return 'W.Num'
      case 'boolean': return 'W.Bool'
      case 'any': return 'W.Any'
    }
  }

  private responseField(node: SchemaNode): string {
    const item = this.responseItem(node)
    switch (item) {
      case 'W.Str': return 'W.str'
      case 'W.Num': return 'W.num'
      case 'W.Bool': return 'W.bool'
      case 'W.Any': return 'W.any'
      default: return `W.field(${item})`
    }
  }

  /** Zoho returns `page_context` as one object; some documents describe it as a list of them. */
  private corrected(name: string, property: SchemaNode): SchemaNode {
    if (name !== 'page_context') return property
    const shape = this.resolve(property)
    return shape.type === 'array' && shape.items !== undefined ? shape.items : property
  }

  private responseStruct(shape: SchemaNode, indent: string): string {
    const fields = Object.entries(shape.properties ?? {}).map(([name, property]) =>
      `${indent}  ${key(name)}: ${this.responseField(this.corrected(name, property)).replace(/\n/g, `\n${indent}`)},`)
    return `Schema.Struct({\n${fields.join('\n')}\n${indent}})`
  }

  private responseDeclaration(component: string): string {
    const name = this.declare(component, 'response')
    if (!this.responseDeclarations.has(name)) {
      this.responseDeclarations.set(name, '')
      const shape = this.merged(this.schema(component))
      const body = this.kind(shape) === 'array'
        ? `W.Arr(${shape.items === undefined ? 'W.Any' : this.responseItem(shape.items)})`
        : this.responseStruct(shape, '')
      this.responseDeclarations.delete(name)
      this.responseDeclarations.set(name, `export const ${name} = ${body}\nexport type ${name} = typeof ${name}.Type\n`)
    }
    return name
  }

  // Requests: plain types, because the caller's own values need no runtime check.

  private inputType(node: SchemaNode, indent: string): string {
    if (node.$ref !== undefined) {
      const component = refName(node.$ref)
      const target = this.schema(component)
      const kind = this.kind(target)
      if (kind === 'object') return this.inputDeclaration(component)
      return this.inputType(target, indent)
    }
    const shape = this.merged(node)
    if (shape.enum !== undefined && shape.enum.length > 0) return shape.enum.map((value) => JSON.stringify(value)).join(' | ')
    switch (this.kind(shape)) {
      case 'array': {
        const item = shape.items === undefined ? 'unknown' : this.inputType(shape.items, indent)
        return `ReadonlyArray<${item}>`
      }
      case 'object': return this.inputObject(shape, indent)
      case 'record': return 'Readonly<Record<string, unknown>>'
      case 'string': return shape.format === 'binary' ? 'ZohoFile' : 'string'
      case 'number': return 'number'
      case 'boolean': return 'boolean'
      case 'any': return 'unknown'
    }
  }

  private inputObject(shape: SchemaNode, indent: string): string {
    const required = new Set(shape.required ?? [])
    const fields = Object.entries(shape.properties ?? {})
      .filter(([, property]) => this.resolve(property).readOnly !== true && property.readOnly !== true)
      .map(([name, property]) =>
        `${comment(this.resolve(property).description ?? property.description, `${indent}  `)}${indent}  readonly ${key(name)}${required.has(name) ? '' : '?'}: ${this.inputType(property, `${indent}  `)}`)
    return fields.length === 0 ? 'Readonly<Record<string, unknown>>' : `{\n${fields.join('\n')}\n${indent}}`
  }

  private inputDeclaration(component: string): string {
    const name = this.declare(component, 'input')
    if (!this.inputDeclarations.has(name)) {
      this.inputDeclarations.set(name, '')
      const body = this.inputObject(this.merged(this.schema(component)), '')
      this.inputDeclarations.delete(name)
      this.inputDeclarations.set(name, body.startsWith('{')
        ? `export interface ${name} ${body}\n`
        : `export type ${name} = ${body}\n`)
    }
    return name
  }

  private hasRequiredProperty(node: SchemaNode): boolean {
    return (this.merged(this.resolve(node)).required ?? []).length > 0
  }

  private parameterType(parameter: ParameterNode): string {
    const schema = parameter.schema === undefined ? undefined : this.resolve(parameter.schema)
    if (schema === undefined) return 'string | number | boolean'
    if (schema.enum !== undefined && schema.enum.length > 0) return schema.enum.map((value) => JSON.stringify(value)).join(' | ')
    switch (schema.type) {
      case 'string': return 'string'
      case 'integer':
      case 'number': return 'number'
      case 'boolean': return 'boolean'
      // Zoho takes structured query values as JSON text; the client serialises them.
      case 'array': return 'ReadonlyArray<unknown>'
      case 'object': return 'Readonly<Record<string, unknown>>'
      default: return 'string | number | boolean'
    }
  }

  private addOperation(template: string, method: (typeof methods)[number], shared: ReadonlyArray<ParameterNode>, node: OperationNode): void {
    const name = camel(node.operationId)
    const inputName = `${pascal(node.operationId)}Input`
    if (this.taken.has(inputName)) throw new Error(`${this.file}: ${inputName} collides with a schema name`)
    this.taken.add(inputName)

    const declared = new Map<string, ParameterNode>()
    for (const reference of [...shared, ...(node.parameters ?? [])]) {
      const parameter = reference.$ref === undefined ? reference : this.parameters[refName(reference.$ref)]
      if (parameter === undefined) throw new Error(`${this.file}: parameter ${reference.$ref} is not defined`)
      // The client supplies the organisation query parameter. A name declared for both the path and the query is the path value.
      if (parameter.name === 'organization_id' && parameter.in === 'query') continue
      const previous = declared.get(parameter.name)
      if (previous === undefined || parameter.in === 'path') declared.set(parameter.name, parameter)
    }

    // Two paths spell a parameter as a regular expression instead of a template name.
    const unnamed = [...declared.values()].filter((parameter) => parameter.in === 'path' && !template.includes(`{${parameter.name}}`))
    const undeclared = [...(undeclaredPathParameters[template] ?? [])]
    const path = template.replace(/\(\\d\+\)/g, () => {
      const parameterName = unnamed.shift()?.name ?? undeclared.shift()
      if (parameterName === undefined) throw new Error(`${this.file}: ${template} has an unnamed segment with no parameter`)
      if (declared.get(parameterName)?.in !== 'path') declared.set(parameterName, { name: parameterName, in: 'path', schema: { type: 'string' } })
      return `{${parameterName}}`
    })
    const inPath = new Set([...path.matchAll(/\{(\w+)\}/g)].map((match) => match[1]!))
    for (const parameter of declared.values()) {
      if (parameter.in === 'path' && !inPath.has(parameter.name)) throw new Error(`${this.file}: ${node.operationId} declares unused path parameter ${parameter.name}`)
    }
    for (const parameterName of inPath) {
      if (declared.get(parameterName)?.in !== 'path') throw new Error(`${this.file}: ${node.operationId} does not declare path parameter ${parameterName}`)
    }
    if (declared.has('body')) throw new Error(`${this.file}: ${node.operationId} has a parameter named body`)

    const fields = [...declared.values()].map((parameter) => {
      const required = parameter.in === 'path' || parameter.required === true
      return `${comment(parameter.description, '  ')}  readonly ${key(parameter.name)}${required ? '' : '?'}: ${this.parameterType(parameter)}`
    })

    const content = node.requestBody?.content ?? {}
    const bodyKind = content['application/json'] !== undefined ? 'json' : content['multipart/form-data'] !== undefined ? 'multipart' : undefined
    if (bodyKind === undefined && Object.keys(content).length > 0) throw new Error(`${this.file}: ${node.operationId} has an unsupported request body`)
    if (bodyKind !== undefined) {
      const bodySchema = content[bodyKind === 'json' ? 'application/json' : 'multipart/form-data']!.schema ?? {}
      const required = node.requestBody?.required === true || this.hasRequiredProperty(bodySchema)
      fields.push(`  readonly body${required ? '' : '?'}: ${this.inputType(bodySchema, '  ')}`)
    }

    const responses = Object.values(node.responses ?? {})
    if (responses.length !== 1) throw new Error(`${this.file}: ${node.operationId} documents ${responses.length} responses`)
    const responseSchema = responses[0]!.content?.['application/json']?.schema
    let response = 'undefined'
    if (responseSchema !== undefined) {
      if (responseSchema.$ref !== undefined) response = this.responseDeclaration(refName(responseSchema.$ref))
      else {
        response = `${pascal(node.operationId)}Response`
        while (this.taken.has(response) || reservedNames.has(response)) response = `${response}_`
        this.taken.add(response)
        this.responseDeclarations.set(response, `export const ${response} = ${this.responseStruct(this.merged(responseSchema), '')}\nexport type ${response} = typeof ${response}.Type\n`)
      }
    }

    const scopes = [...new Set((node.security ?? []).flatMap((requirement) => Object.values(requirement).flat()))]
    const headers = [...declared.values()].filter((parameter) => parameter.in === 'header').map((parameter) => parameter.name)
    const definition = [
      `id: ${JSON.stringify(node.operationId)}`,
      `method: ${JSON.stringify(method.toUpperCase())}`,
      `path: ${JSON.stringify(path)}`,
      ...(headers.length === 0 ? [] : [`headers: ${JSON.stringify(headers)}`]),
      ...(bodyKind === undefined ? [] : [`body: ${JSON.stringify(bodyKind)}`]),
      `response: ${response}`,
      `scopes: ${JSON.stringify(scopes)}`,
    ]
    const summary = `${node.summary ?? node.operationId}. \`${method.toUpperCase()} ${path}\`${node.deprecated === true ? ' @deprecated' : ''}`
    this.operations.push([
      fields.length === 0 ? `export interface ${inputName} {}\n` : `export interface ${inputName} {\n${fields.join('\n')}\n}\n`,
      `${comment(summary, '')}export const ${name} = /*#__PURE__*/ operation<${inputName}, ${response === 'undefined' ? 'undefined' : `typeof ${response}`}>({\n${definition.map((line) => `  ${line},`).join('\n')}\n})\n`,
    ].join('\n'))
  }

  render(): string {
    for (const [template, item] of Object.entries(this.document.paths)) {
      const shared = (item['parameters'] ?? []) as ReadonlyArray<ParameterNode>
      for (const method of methods) {
        const node = item[method] as OperationNode | undefined
        if (node !== undefined) this.addOperation(template, method, shared, node)
      }
    }
    const body = [...this.responseDeclarations.values(), ...this.inputDeclarations.values(), ...this.operations].join('\n')
    return [
      banner,
      ...(this.responseDeclarations.size > 0 ? ["import * as Schema from 'effect/Schema'", "import * as W from '../../internal/wire.ts'"] : []),
      `import { operation${/\bZohoFile\b/.test(body) ? ', type ZohoFile' : ''} } from '../Operation.ts'`,
      '',
      body,
    ].join('\n')
  }
}

const files = readdirSync(specDirectory).filter((file) => file.endsWith('.yml')).sort()
const outputs = new Map<string, string>()
const moduleNames: string[] = []
const operationIds = new Set<string>()
for (const file of files) {
  const document = parse(readFileSync(join(specDirectory, file), 'utf8')) as Document
  for (const item of Object.values(document.paths)) {
    for (const method of methods) {
      const id = (item[method] as OperationNode | undefined)?.operationId
      if (id === undefined) continue
      if (operationIds.has(id)) throw new Error(`${file}: operationId ${id} is not unique across modules`)
      operationIds.add(id)
    }
  }
  const module = new Module(file, document)
  outputs.set(join(outputDirectory, `${module.name}.ts`), module.render())
  moduleNames.push(module.name)
}
outputs.set(indexFile, [
  banner,
  "export * from './Operation.ts'",
  "export * from './ZohoBooksClient.ts'",
  ...moduleNames.map((name) => `export * as ${name} from './generated/${name}.ts'`),
  '',
].join('\n'))

if (process.argv.includes('--check')) {
  const stale = [...outputs].filter(([path, content]) => !existsSync(path) || readFileSync(path, 'utf8') !== content).map(([path]) => path)
  const extra = existsSync(outputDirectory)
    ? readdirSync(outputDirectory).map((file) => join(outputDirectory, file)).filter((path) => !outputs.has(path))
    : []
  if (stale.length + extra.length > 0) {
    console.error(`Generated code is out of date. Run \`bun run generate\`.\n${[...stale, ...extra].join('\n')}`)
    process.exit(1)
  }
} else {
  rmSync(outputDirectory, { recursive: true, force: true })
  mkdirSync(outputDirectory, { recursive: true })
  for (const [path, content] of outputs) writeFileSync(path, content)
  console.log(`Generated ${operationIds.size} operations in ${moduleNames.length} modules.`)
}
